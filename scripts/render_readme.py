"""Render the README Key findings block from data/processed/.

    python scripts/render_readme.py          # rewrite the block in README.md
    python scripts/render_readme.py --check  # exit 1 if README.md is out of date
"""
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
P = ROOT / "data" / "processed"
START = "<!-- results:start (generated by scripts/render_readme.py, do not edit by hand) -->"
END = "<!-- results:end -->"


def render() -> str:
    k = pd.read_csv(P / "kupiec_results.csv")
    c = pd.read_csv(P / "christoffersen_results.csv")
    a = pd.read_csv(P / "stress_amplification.csv")
    pl = pd.read_csv(P / "placebo_comparison.csv")
    k = k[k.slice == "full_sample"].set_index("bank")
    c = c[c["sample"] == "full_sample"].pivot(index="bank", columns="test", values="p_value")
    a = a[a.year.astype(str) == "all"].set_index("bank")
    banks = sorted(k.index)

    o = ["Full sample 2019 to 2024, headline (absolute-return) violation definition. p-values below 0.05 reject.", "",
         "| Bank | Stated rate | Actual rate | Kupiec p | Christoffersen IND p | CC p | Stress / calm violation ratio |",
         "|---|---|---|---|---|---|---|"]
    for b in banks:
        o.append(f"| {b} | {k.loc[b, 'stated_rate']:.0%} | {k.loc[b, 'actual_rate']:.2%} | {k.loc[b, 'p_value']:.3f} | "
                 f"{c.loc[b, 'IND']:.3f} | {c.loc[b, 'CC']:.3f} | {a.loc[b, 'amplification']:.1f}x |")
    n_cc = int((c.loc[banks, "CC"] < 0.05).sum())

    piv = pl.pivot(index="bank", columns="threshold")
    o += ["", "**Placebo test** (`analysis/placebo.py`): the same tests on thresholds with the same average level per bank. "
          "mcap_only keeps the market-cap scaling but replaces disclosed VaR with the bank's sample average; "
          "constant uses one fixed threshold.", "",
          "| Bank | Stress / calm ratio: disclosed | mcap_only | constant | Clustering LR_ind: disclosed | mcap_only | constant |",
          "|---|---|---|---|---|---|---|"]
    for b in banks:
        am, li = piv.loc[b, "amplification"], piv.loc[b, "lr_ind"]
        o.append(f"| {b} | {am['disclosed']:.1f}x | {am['mcap_only']:.1f}x | {am['constant']:.1f}x | "
                 f"{li['disclosed']:.1f} | {li['mcap_only']:.1f} | {li['constant']:.1f} |")
    beats_const = int((piv["amplification"]["disclosed"] < piv["amplification"]["constant"]).sum())
    beats_mcap_ind = int((piv["lr_ind"]["disclosed"] < piv["lr_ind"]["mcap_only"]).sum())
    o += ["",
          f"- Conditional coverage rejects at 5% for {n_cc} of {len(banks)} banks.",
          f"- Disclosed VaR has a lower stress / calm violation ratio than a constant threshold for {beats_const} of {len(banks)} banks, "
          "so the disclosures do respond to stress rather than ignoring it.",
          f"- On clustering, disclosed VaR beats the mcap_only placebo, which contains no disclosure information, for {beats_mcap_ind} of {len(banks)} banks. "
          "Independence rejections therefore cannot be attributed to the banks' VaR models: much of the threshold's movement comes from "
          "the market-cap scaling, which rises when the bank's own stock falls."]
    return "\n".join(o)


def main():
    readme = ROOT / "README.md"
    text = readme.read_text()
    pre, rest = text.split(START, 1)
    _, post = rest.split(END, 1)
    new = pre + START + "\n" + render() + "\n" + END + post
    if "--check" in sys.argv:
        if new != text:
            sys.exit("README.md Key findings are out of date. Run: python scripts/render_readme.py")
        print("README.md Key findings match data/processed/")
        return
    readme.write_text(new)
    print(render())


if __name__ == "__main__":
    main()
